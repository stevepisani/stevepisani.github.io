import assert from 'node:assert/strict';
import { wardrobeDb, STEVE } from './wardrobe-db.mjs';
const {db,q}=await wardrobeDb();
await db.exec("grant usage on schema public,auth to authenticated,anon; update public.members set finance_enabled=true where email='steve@example.com'");
await q("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:STEVE,email:'steve@example.com'})]);
await db.exec('set role authenticated');
const call=p=>q('select public.finance_import($1::jsonb) as result',[JSON.stringify(p)]);
const account={source_key:'bank:one',name:'Example checking',kind:'cash',balance_cents:1000000,as_of:new Date().toISOString()};
const transaction={account_source_key:'bank:one',source_key:'receipt:one',posted_on:'2026-01-02',description:'Example payment',amount_cents:10000,treatment:'business_income'};
const plan={year:2026,monthly_target_cents:200000,retirement_goal_cents:100000,tax_reserve_cents:100000,contractor_reserve_cents:20000,operations_reserve_cents:10000,household_reserve_cents:200000,expected_receipts_cents:100000,reviewed_on:'2026-01-01',assumptions:'Synthetic assumption'};
const payload={schema_version:1,accounts:[account],transactions:[transaction],plans:[plan],budgets:[{month:'2026-01-01',category:'Food',target_cents:25000}],scenarios:[{year:2026,source_key:'one',name:'Example scenario',profit_cents:1000000,federal_cents:200000,state_cents:50000,paid_cents:10000,retirement_cents:100000,assumptions:'Synthetic estimate',reviewed_on:'2026-01-01'}]};
await call(payload);
for(const t of ['accounts','transactions','plans','budgets','tax_scenarios'])assert.equal((await q(`select * from finance_${t}`)).length,1);
await q("update finance_transactions set treatment='transfer',note='Reviewed correction'");
await q('update finance_plans set monthly_target_cents=300000');
await call(payload);
assert.equal((await q('select * from finance_transactions')).length,1);
assert.equal((await q('select treatment from finance_transactions'))[0].treatment,'transfer');
assert.equal(Number((await q('select monthly_target_cents from finance_plans'))[0].monthly_target_cents),300000);
await assert.rejects(()=>call({...payload,transactions:[{...transaction,amount_cents:9999}]}),/differs/);
await assert.rejects(()=>call({...payload,accounts:[{...account,owner:STEVE}]}),/Unknown record/);
await assert.rejects(()=>call({...payload,accounts:[{...account,balance_cents:0.5}]}),/integer cents/);
await assert.rejects(()=>call({...payload,transactions:[{...transaction,account_source_key:'missing'}]}),/Account not found/);
await assert.rejects(()=>call({...payload,accounts:[{...account,balance_cents:123}],transactions:[{...transaction,amount_cents:999}]}),/differs/);
assert.equal(Number((await q('select balance_cents from finance_accounts'))[0].balance_cents),1000000);
await assert.rejects(()=>call({schema_version:1,plans:'bad'}),/arrays/);
await call({schema_version:1,transactions:[{...transaction,source_key:'csv:td:example'}]});
await assert.rejects(()=>call({schema_version:1,transactions:[{...transaction,source_key:'csv:monarch:other'}]}),/existing CSV provider/);
await db.exec('reset role;set role anon');
await assert.rejects(()=>call(payload),/permission denied/);
await db.exec('reset role');
await q("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:STEVE,email:'steve@example.com',client_id:'wardrobe'})]);
await db.exec('set role authenticated');
await assert.rejects(()=>call(payload),/Finance access required/);
await db.close();
console.log('Finance imports: all record types, duplicates, preserved corrections, atomic rollback, invalid amounts and access controls passed.');
